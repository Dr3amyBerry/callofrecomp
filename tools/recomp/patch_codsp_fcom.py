#!/usr/bin/env python3
"""Opt-in CoDSP 1.5 exact full x87 FCOM+pop lowering in private p1/p8.

This fail-closed patch never changes the number of generated C source lines;
all supported instruction shapes are fingerprinted against their original
p-code bodies. No original executable, game asset or generated source is
published. Default build keeps executing the original block.
"""
from __future__ import annotations
import hashlib
from pathlib import Path
import re
import argparse

EXPECTED = {"codsp_recomp_p1.c": 226, "codsp_recomp_p8.c": 222}
HEADER = "// Generated by tools/recomp/pcode2c.py from CoDSP.exe. Do not commit."
MARKER = "CODSP_FCOM_GUARD("
OLD_INCLUDE = '#include "x87_nan_bits.h"\n'
NEW_INCLUDE = '#include "codsp_fcom.h"\n'
ANCHOR = ' wr(guest_regs+0x1091,1,(u128)0x0ULL);\n'
LABEL = re.compile(r"(?m)^L_([0-9a-f]+):\n")
SUFFIXES = {
    "42": "b93d7040902b74abda6df214b60131d949d5c118c17bc66744d7970a28eb4300",
    "34": "c5c11d80a159e40d51217b5abb2ed313a60db5792ebde515feaf0c2ded8a5f02",
    "38": "29416d511d8222e85c0311601f7056172402ad8ffe21cf83f4525e3ae8b9629f",
}

# A binary32 memory scalar is calculated via an original address expression
# (sum of one 32-bit guest register and an unsigned immediate).
REG = r"rd\(guest_regs\+0x[0-9a-f]+,4\)"
IMM = r"\(u128\)0x[0-9a-f]+ULL"
ADDR = re.compile(rf"\(?{REG}\+{IMM}\)?|\(?{IMM}\+{REG}\)?")
PREFIX_42 = re.compile(
    r"^ \{ uint8_t T\[42\];\n"
    r" wr\(T\+0,4,mask\(\((.+)\),4\)\);\n"
    r" wr\(guest_regs\+0x10ac,4,\(u128\)0x([0-9a-f]+)ULL\);\n"
    r" wr\(T\+4,4,rd\(GR\(\(uint32_t\)rd\(T\+0,4\)\),4\)\);\n"
    r" wr\(T\+32,10,d2f\(\(f2d\(rd\(T\+4,4\),4\)\),10\)\);\n$"
)
PREFIX_34 = re.compile(
    r"^ \{ uint8_t T\[34\];\n"
    r" wr\(guest_regs\+0x10ac,4,\(u128\)0x([0-9a-f]+)ULL\);\n"
    r" wr\(T\+24,10,d2f\(\(f2d\(rd\(GR\((0x[0-9a-f]+)u\),4\),4\)\),10\)\);\n$"
)
PREFIX_38 = re.compile(
    r"^ \{ uint8_t T\[38\];\n"
    r" wr\(guest_regs\+0x10ac,4,\(u128\)0x([0-9a-f]+)ULL\);\n"
    r" wr\(T\+0,4,rd\(GR\(\(uint32_t\)rd\(guest_regs\+(0x[0-9a-f]+),4\)\),4\)\);\n"
    r" wr\(T\+28,10,d2f\(\(f2d\(rd\(T\+0,4\),4\)\),10\)\);\n$"
)

def identify(block: str, pc: str):
    if block.count(ANCHOR) != 1:
        return None
    prefix, suffix = block.split(ANCHOR, 1)
    checksum = hashlib.sha256(suffix.encode("utf-8")).hexdigest()
    if checksum not in SUFFIXES.values():
        return None
    if checksum == SUFFIXES["42"]:
        match = PREFIX_42.fullmatch(prefix)
        if not match or not ADDR.fullmatch(match[1]):
            return None
        if match[2] != pc:
            raise ValueError(f"unexpected dynamic FCOM pc at {pc}")
        return "42", f"(uint32_t)mask(({match[1]}),4)"
    if checksum == SUFFIXES["34"]:
        match = PREFIX_34.fullmatch(prefix)
        if not match:
            return None
        if match[1] != pc:
            raise ValueError(f"unexpected immediate FCOM pc at {pc}")
        return "34", match[2] + "u"
    match = PREFIX_38.fullmatch(prefix)
    if not match:
        return None
    if match[1] != pc:
        raise ValueError(f"unexpected register FCOM pc at {pc}")
    return "38", f"(uint32_t)rd(guest_regs+{match[2]},4)"

def patch(contents: str, filename: str, *, expected: int | None = None):
    if filename not in EXPECTED:
        raise ValueError("Only verified private CoDSP p1 and p8 supported")
    count = EXPECTED[filename] if expected is None else expected
    if not contents.startswith(HEADER):
        raise ValueError("Not original CoDSP 1.5 generated source")
    candidates = list(LABEL.finditer(contents))
    found = 0
    already = 0
    writes = []
    for i,match in enumerate(candidates[:-1]):
        start,end=match.end(),candidates[i+1].start()
        block=contents[start:end]
        pc=match.group(1)
        if MARKER in block:
            already += block.count(MARKER)
            continue
        info=identify(block,pc)
        if info is None:
            continue
        shape,addr=info
        next_pc=candidates[i+1].group(1)
        token=f" {{ uint8_t T[{shape}];"
        if block.count(token) != 1:
            raise ValueError(f"unexpected block start at {pc}")
        transformed=block.replace(token,
            f" {{ if (CODSP_FCOM_GUARD(guest_regs, guest_mem, 0x{pc}u, {addr})) goto L_{next_pc}; uint8_t T[{shape}];",1)
        if transformed.count("\n") != block.count("\n"):
            raise ValueError("DWARF provenance line shift")
        writes.append((start,end,transformed))
        found += 1
    if already == count and found == 0 and contents.count(NEW_INCLUDE) == 1:
        return contents,False
    if found != count or already != 0 or contents.count(OLD_INCLUDE) != 1 or contents.count(NEW_INCLUDE):
        raise ValueError(f"partial/stale C: found={found}, previously={already}, wanted={count}")
    # Apply backward so original source spans stay stable.
    result=contents
    for start,end,block in reversed(writes):
        result=result[:start]+block+result[end:]
    result=result.replace(OLD_INCLUDE,NEW_INCLUDE,1)
    if result.count("\n")!=contents.count("\n"):
        raise ValueError("source line provenance changed")
    return result,True

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("files",nargs="+",type=Path)
    args=p.parse_args()
    if {v.name for v in args.files} != set(EXPECTED) or len(args.files)!=2:
        p.error("Pass original private CoDSP p1/p8 only")
    pending=[]
    for f in args.files:
        if not f.is_file() or f.parent.name != "recomp_out":
            p.error("Only existing private recomp_out sources permitted")
        new,modified=patch(f.read_text("utf-8"),f.name)
        pending.append((f,new,modified))
    for f,new,modified in pending:
        if modified:f.write_text(new,encoding="utf-8",newline="\n")
        print(f.name,"patched" if modified else "already patched")
    print("Original comparison remains active unless CODRECOMP_X87_FCOM_FASTPATH is set")
if __name__=="__main__":
    main()
