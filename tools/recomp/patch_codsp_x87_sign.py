#!/usr/bin/env python3
"""Reversible opt-in ARM64 FCHS sign-bit patch for three verified CoDSP PCs.

Exact p-code provenance and exact generated-site C required. Only the highest
bit of the tenth binary80 byte is XORed. Does not alter CW/SW/TOP/tags.
This models the FLOAT_NEG *value* specified by this p-code, not every x87
FCHS exception/status corner case of the original hardware. OFF by default.
"""
from __future__ import annotations

import argparse
from hashlib import sha256
from pathlib import Path

PCODE_SHA256 = "36f9093b386e03b4bcdc489cff2a708f7c0b8012e9a0fa78a7001bd3f125da1e"
SOURCE_HEADER = "// Generated by tools/recomp/pcode2c.py from CoDSP.exe. Do not commit."
PC_SITES = (0x41975e, 0x419c48, 0x419e12)
OLD = " wr(guest_regs+0x1100,10,d2f(-(f2d(rd(guest_regs+0x1100,10),10)),10));"
NEW = (" wr(guest_regs+0x1109,1,(rd(guest_regs+0x1109,1) ^ (u128)0x80u));"
       " /* CODSP_X87_SIGN_BIT_FCHS */")


def _validate_line_endings(source: bytes) -> None:
    if b"\r\n" in source and source.count(b"\r\n") != source.count(b"\n"):
        raise ValueError("Mixed line endings")


def transform(source: bytes, *, apply: bool) -> tuple[bytes, tuple[int, ...]]:
    if not source.startswith(SOURCE_HEADER.encode("utf8") + b"\n") and not source.startswith(
            SOURCE_HEADER.encode("utf8") + b"\r\n"):
        raise ValueError("Requires original CoDSP generated source header")
    _validate_line_endings(source)
    lines = source.decode("utf8").splitlines(keepends=True)
    result = list(lines)
    count = []
    for pc in PC_SITES:
        tag = f"L_{pc:x}:"
        indices = [idx for idx, line in enumerate(lines) if line.strip() == tag]
        if len(indices) != 1:
            raise ValueError(f"PC {pc:08x} not unique in this partition")
        idx = indices[0]
        # The original instruction has only PC COPY and FLOAT_NEG. We do not
        # touch a site with other operations or a different register view.
        expected_pc = f" wr(guest_regs+0x10ac,4,(u128)0x{pc:x}ULL);"
        instruction = [line.rstrip("\r\n") for line in lines[idx+1:idx+5]]
        if expected_pc not in instruction:
            raise ValueError(f"Unexpected original PC update at {pc:08x}")
        actual = OLD if apply else NEW
        replacement = NEW if apply else OLD
        found = [k for k in range(idx+1, min(idx+5,len(lines)))
                 if lines[k].rstrip("\r\n") == actual]
        if len(found) != 1:
            # Restore should be harmless for already unpatched source, but
            # must not tolerate a mixture of modified and original sites.
            if not apply and OLD in instruction and NEW not in instruction:
                count.append(pc)
                continue
            raise ValueError(f"Unexpected generated FLOAT_NEG at {pc:08x}")
        k = found[0]
        ending = "\r\n" if lines[k].endswith("\r\n") else "\n"
        result[k] = replacement + ending
        count.append(pc)
    if len(count) != len(PC_SITES):
        raise ValueError("Incomplete patch selection")
    edited = "".join(result).encode("utf8")
    if len(result) != len(lines):
        raise AssertionError("Generated C source line numbering changed")
    if edited.count(NEW.encode()) != (3 if apply else 0):
        raise ValueError("Unexpected patched marker count")
    return edited, tuple(count)


def main(argv=None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("source", type=Path)
    parser.add_argument("pcode", type=Path)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--apply",action="store_true")
    mode.add_argument("--restore",action="store_true")
    args=parser.parse_args(argv)
    if args.source.name != "codsp_recomp_p0.c":
        parser.error("Only verified CoDSP partition p0 can be patched")
    if sha256(args.pcode.read_bytes()).hexdigest() != PCODE_SHA256:
        parser.error("Unknown p-code hash; require original CoDSP 1.5")
    before=args.source.read_bytes()
    after,pcs=transform(before,apply=args.apply)
    if before!=after:
        stage=args.source.with_name(args.source.name+".sign.tmp")
        if stage.exists():
            raise RuntimeError("Refuse existing staging path")
        try:
            stage.write_bytes(after)
            if stage.read_bytes()!=after:
                raise RuntimeError("Staging verification failed")
            stage.replace(args.source)
        finally:
            if stage.exists():stage.unlink()
    print("ARM64_X87_FCHS_BITS", "apply" if args.apply else "restore",
          "pcs",*[hex(pc) for pc in pcs],
          "changed",before!=after,"sha256",sha256(after).hexdigest())


if __name__=="__main__":main()
