#!/usr/bin/env python3
"""Opt-in binary80 NaN classification for private, generated CoDSP 1.5 p1/p8.

Replace ONLY exact isnan(f2d(rd(...,10),10)) generated p-code forms,
without changing source line count or any floating-point arithmetic.
The generated code remains ignored. Wrong module, changed count/labels and
partial previous replacements fail closed.
"""
from __future__ import annotations
import argparse
from pathlib import Path
import re

EXPECTED = {
    "codsp_recomp_p1.c": (632, "L_41b8f0:"),
    "codsp_recomp_p8.c": (546, "L_4d8280:"),
}
HEADER = "// Generated by tools/recomp/pcode2c.py from CoDSP.exe. Do not commit."
INCLUDE = '#include "x87_nan_bits.h"\n'
FCOM_INCLUDE = '#include "codsp_fcom.h"\n'
FCOM_SITES = {"codsp_recomp_p1.c": 226, "codsp_recomp_p8.c": 222}
BEFORE = re.compile(
    r'isnan\(f2d\((rd\((?:T\+\d+|guest_regs\+0x[0-9a-f]+|R\+0x[0-9a-f]+),10\)),10\)\)'
)
AFTER = re.compile(r'CODSP_X87_ISNAN\(rd\((?:T\+\d+|guest_regs\+0x[0-9a-f]+|R\+0x[0-9a-f]+),10\)\)')


def patch(contents: str, name: str, *, expected: int | None = None) -> tuple[str, bool]:
    if name not in EXPECTED:
        raise ValueError("Only CoDSP 1.5 private p1/p8 are supported")
    count, sentinel = EXPECTED[name]
    if expected is not None:
        count = expected  # unit tests with synthetic C, never used from CLI
    if not contents.startswith(HEADER) or contents.count(sentinel) != 1:
        raise ValueError("Wrong CoDSP C version or missing function entry")
    existing_runtime = contents.count('#include "recomp_rt.h"\n')
    existing_helper = contents.count(INCLUDE)
    existing_fcom = contents.count(FCOM_INCLUDE)
    if existing_runtime + existing_helper + existing_fcom != 1:
        raise ValueError("Ambiguous runtime include")
    if existing_fcom and contents.count('CODSP_FCOM_GUARD(') != FCOM_SITES[name]:
        raise ValueError("FCOM wrapper found without complete verified injection")
    original = len(BEFORE.findall(contents))
    changed = len(AFTER.findall(contents))
    if contents.count(INCLUDE) > 1:
        raise ValueError("Duplicated helper include")
    if original == 0 and changed == count and (existing_helper == 1 or existing_fcom == 1):
        return contents, False
    if original != count or changed != 0 or existing_helper != 0 or existing_fcom != 0:
        raise ValueError(f"Stale/partial private C: original={original}, patched={changed}, wanted={count}")
    converted, done = BEFORE.subn(r'CODSP_X87_ISNAN(\1)', contents)
    if done != count:
        raise ValueError("Unexpected number of replacements")
    # Swap an include line instead of adding one, keeping native DWARF
    # source-line locations unchanged for real device profiler attribution.
    converted = converted.replace('#include "recomp_rt.h"\n', INCLUDE, 1)
    if converted.count("\n") != contents.count("\n"):
        raise ValueError("Line number provenance changed")
    return converted, True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('files', type=Path, nargs='+')
    args = parser.parse_args()
    if {p.name for p in args.files} != set(EXPECTED) or len(args.files) != len(EXPECTED):
        parser.error("Pass both original p1 and p8 generated CoDSP files")
    all_writes = []
    for file in args.files:
        if file.parent.name != 'recomp_out' or not file.is_file():
            parser.error("Only existing private recomp_out/codsp_recomp_p1/p8.c are allowed")
        result, modified = patch(file.read_text(encoding='utf-8'), file.name)
        all_writes.append((file, result, modified))
    # Never partially patch p1 if p8 validation fails.
    for file, result, modified in all_writes:
        if modified:
            file.write_text(result, encoding='utf-8', newline='\n')
        print(file.name, "patched" if modified else "already patched")
    print("Compiles as original unless CODRECOMP_X87_NAN_BITS is defined")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
