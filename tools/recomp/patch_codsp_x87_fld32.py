#!/usr/bin/env python3
"""Reversible CoDSP 1.5 ARM64 float32->binary80 normal-input specialization.

Only 39 exact FLOAT2FLOAT u/r:4->10 sites in original hot function 0x5061b0.
The guest LOAD and all x87 pushes/stores keep their exact source order.
Unknown generated C, p-code or mixed states fail closed. OFF by default.
"""
from __future__ import annotations
import argparse
from hashlib import sha256
from pathlib import Path
import re

PCODE_SHA256 = "36f9093b386e03b4bcdc489cff2a708f7c0b8012e9a0fa78a7001bd3f125da1e"
SOURCE_SHA256 = "629f468b39649875971ed02f18114390cdc7a12ff1871ac33fd9c30006635fd5"
SOURCE_HEADER = "// Generated by tools/recomp/pcode2c.py from CoDSP.exe. Do not commit."
PC_SITES = (
    0x5061b0, 0x5061b3, 0x5061b6, 0x5061b8, 0x5061bc, 0x5061bf,
    0x5061c4, 0x5061c9, 0x5061cc, 0x5061cf, 0x5061d2, 0x5061d7,
    0x5061da, 0x5061de, 0x5061e4, 0x5061e7, 0x5061ea, 0x5061ed,
    0x5061f2, 0x5061f5, 0x5061f9, 0x5061ff, 0x506202, 0x506205,
    0x506207, 0x50620b, 0x50620e, 0x506215, 0x506218, 0x50621a,
    0x50621d, 0x506222, 0x506225, 0x50622d, 0x506230, 0x506232,
    0x506235, 0x50623a, 0x50623d,
)
MARKER = "CODSP_X87_FLD32_NORMAL"
# This is the exact emitted expression, never a generic float rewrite.
OLD_RE = re.compile(r"d2f\(\(f2d\((rd\(T\+\d+,4\)),4\)\),10\)")
NEW_RE = re.compile(
    r"codsp_x87_fld32_normal\((rd\(T\+\d+,4\))\) /\* " +
    MARKER + r" \*/"
)


def _replace_line(line: str, *, apply: bool) -> str:
    if apply:
        return OLD_RE.sub(
            lambda m: f"codsp_x87_fld32_normal({m[1]}) /* {MARKER} */",
            line,
        )
    return NEW_RE.sub(lambda m: f"d2f((f2d({m[1]},4)),10)", line)


def transform(source: bytes, *, apply: bool) -> tuple[bytes, tuple[int, ...]]:
    if not (source.startswith(SOURCE_HEADER.encode() + b"\n") or
            source.startswith(SOURCE_HEADER.encode() + b"\r\n")):
        raise ValueError("Expected original CoDSP generated source header")
    if (source.count(b"\r\n") not in (0, source.count(b"\n")) or
            source.count(b"\r") != source.count(b"\r\n")):
        raise ValueError("Mixed/invalid generated C line endings")
    lines = source.decode("utf8").splitlines(keepends=True)
    rewritten = list(lines)
    labels = {
        ln.strip(): idx for idx, ln in enumerate(lines)
        if ln.strip().startswith("L_") and ln.strip().endswith(":")
    }
    if len(PC_SITES) != 39:
        raise ValueError("Unexpected verified hot-PC count")
    for pc in PC_SITES:
        tag = f"L_{pc:x}:"
        idx = labels.get(tag)
        if idx is None or sum(ln.strip() == tag for ln in lines) != 1:
            raise ValueError(f"Missing or repeated target {pc:08x}")
        end = next(
            (i for i in range(idx + 1, len(lines))
             if lines[i].lstrip().startswith("L_") and lines[i].rstrip().endswith(":")),
            len(lines),
        )
        block = lines[idx + 1:end]
        pc_store = f" wr(guest_regs+0x10ac,4,(u128)0x{pc:x}ULL);"
        if sum(line.rstrip("\r\n") == pc_store for line in block) != 1:
            raise ValueError(f"Missing original PC update at {pc:08x}")
        target = OLD_RE if apply else NEW_RE
        hits = [i for i in range(idx + 1, end) if target.search(lines[i])]
        if len(hits) != 1 or len(target.findall(lines[hits[0]])) != 1:
            raise ValueError(f"Expected exactly one verified conversion at {pc:08x}")
        rewritten[hits[0]] = _replace_line(lines[hits[0]], apply=apply)
    edited = "".join(rewritten).encode("utf8")
    if edited.count(MARKER.encode()) != (39 if apply else 0):
        raise ValueError("Unexpected marker count")
    if len(edited.splitlines()) != len(source.splitlines()):
        raise ValueError("Generated C PC-to-line mapping changed")
    return edited, PC_SITES


def transform_file(source: bytes, *, apply: bool) -> tuple[bytes, tuple[int, ...]]:
    digest = sha256(source).hexdigest()
    markers = source.count(MARKER.encode())
    if apply:
        if digest != SOURCE_SHA256 or markers:
            raise ValueError("Unknown or previously patched CoDSP p10 source")
    elif markers == 0:
        if digest != SOURCE_SHA256:
            raise ValueError("Unknown source without patch markers")
        return source, PC_SITES
    elif markers != 39:
        raise ValueError("Mixed/partial FLD32 patch: refuse restoring")
    after, sites = transform(source, apply=apply)
    if not apply and sha256(after).hexdigest() != SOURCE_SHA256:
        raise ValueError("Cannot exactly restore baseline CoDSP source")
    return after, sites


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("source", type=Path)
    ap.add_argument("pcode", type=Path)
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--apply", action="store_true")
    mode.add_argument("--restore", action="store_true")
    args = ap.parse_args(argv)
    if args.source.name != "codsp_recomp_p10.c":
        ap.error("Only verified CoDSP p10 can be patched")
    if sha256(args.pcode.read_bytes()).hexdigest() != PCODE_SHA256:
        ap.error("Unknown p-code SHA; requires original CoDSP 1.5")
    before = args.source.read_bytes()
    after, sites = transform_file(before, apply=args.apply)
    if after != before:
        stage = args.source.with_name(args.source.name + ".fld32.tmp")
        if stage.exists():
            raise ValueError("Refuse existing staging path")
        try:
            stage.write_bytes(after)
            if stage.read_bytes() != after:
                raise IOError("Staging bytes mismatch")
            stage.replace(args.source)
        finally:
            if stage.exists():
                stage.unlink()
    print("ARM64_X87_FLD32_NORMAL", "apply" if args.apply else "restore",
          "sites", len(sites), "changed", before != after,
          "sha256", sha256(after).hexdigest())


if __name__ == "__main__":
    main()
