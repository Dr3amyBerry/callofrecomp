#!/usr/bin/env python3
"""Reversible, hash-pinned narrow INT_LEFT opt-in for original CoDSP p0/p8.

Only guest-PC-audited variable-shift sites in the two hot geometry/visibility
ranges. Fixed-count shifts are deliberately excluded: LLVM already folds them.
No index, label, guest memory operation, or instruction order is modified.
"""
from __future__ import annotations

import argparse
from hashlib import sha256
from pathlib import Path
import re
import sys

from pcode2c import Gen, parse, temporary_layout

PCODE_SHA256 = "36f9093b386e03b4bcdc489cff2a708f7c0b8012e9a0fa78a7001bd3f125da1e"
SOURCE_SHA256 = {
    0: "e0ed2e6a861104460f2413fae06b5074d5dddf2a95ba4896c6bef47552fffb02",
    8: "7532b4222eb40b37c5e8bb5491babe3250756f263f5cc2e9b73f2fba7501bdca",
}
TARGET_RANGES = {
    0: (0x004196F0, 0x00419ED6),
    8: (0x004D8000, 0x004D9600),
}
MARKER = "CODSP_ARM64_NARROW_LEFT"
SOURCE_HEADER = "// Generated by tools/recomp/pcode2c.py from CoDSP.exe. Do not commit."
LABEL = re.compile(r"L_[0-9a-f]+:")
EXPECTED_TOTAL = 16


def _sha(data: bytes) -> str:
    return sha256(data).hexdigest()


def _exact_lines(blob: bytes) -> list[str]:
    if not (blob.startswith((SOURCE_HEADER + "\n").encode())
            or blob.startswith((SOURCE_HEADER + "\r\n").encode())):
        raise ValueError("Source is not pinned CoDSP generated C")
    if (blob.count(b"\r\n") not in (0, blob.count(b"\n"))
            or blob.count(b"\r") != blob.count(b"\r\n")):
        raise ValueError("Refusing mixed source line endings")
    return blob.decode("utf8").splitlines(keepends=True)


def plan(pcode: Path):
    """Audit opcode, width, alias, generated expression, and PC identity."""
    if _sha(pcode.read_bytes()) != PCODE_SHA256:
        raise ValueError("Unknown original CoDSP p-code")
    original, _, _ = parse(pcode)
    plan_by_part = {0: [], 8: []}
    for pc, length, ops in original:
        part = next((p for p, (lo, hi) in TARGET_RANGES.items()
                     if lo <= pc < hi), None)
        if part is None:
            continue
        local = temporary_layout(ops)
        if local is None:
            raise ValueError(f"Unproven temporaries at guest PC {pc:08x}")
        g = Gen({})
        g.temp_offsets = local
        for i, (mn, out, ins) in enumerate(ops):
            if mn != "INT_LEFT" or ins[1][0] == "c":
                continue
            if (out is None or out[2] not in (1, 2, 4, 8)
                    or len(ins) != 2
                    or any(v is None or v[0] == "m" for v in ins)):
                raise ValueError(f"Nonconforming variable shift at {pc:08x}:{i}")
            a, b = g.rd(ins[0]), g.rd(ins[1])
            old = f"shl({a},{b})"
            new = f"codsp_arm64_narrow_shl({a},{b},{out[2]})"
            before = g.op(mn, out, ins, None, None)
            if before.count(old) != 1:
                raise ValueError(f"Cannot locate original shift at {pc:08x}:{i}")
            replace = before.replace(old, new, 1)
            # Original C is compiled with disjoint register/memory aliases.
            before = before.replace("R+", "guest_regs+").replace("G(", "GR(")
            replace = replace.replace("R+", "guest_regs+").replace("G(", "GR(")
            plan_by_part[part].append((pc, i, before, replace))
    if sum(len(x) for x in plan_by_part.values()) != EXPECTED_TOTAL:
        raise ValueError("Original hot variable-shift count changed")
    if not all(plan_by_part.values()):
        raise ValueError("Expected a change in both CoDSP partitions")
    return plan_by_part


def transform(blob: bytes, *, part: int, replacements, apply: bool) -> bytes:
    """Rewrite every exact statement, fail closed on duplicate/partial blocks."""
    if part not in SOURCE_SHA256:
        raise ValueError("Invalid CoDSP part")
    lines = _exact_lines(blob)
    original_labels = {}
    for i, line in enumerate(lines):
        text = line.strip()
        if LABEL.fullmatch(text):
            if text in original_labels:
                raise ValueError("Duplicate guest label")
            original_labels[text] = i
    edited = list(lines)
    for pc, op_i, old, new in replacements:
        if not TARGET_RANGES[part][0] <= pc < TARGET_RANGES[part][1]:
            raise ValueError("Out-of-region patch site")
        start = original_labels.get(f"L_{pc:x}:")
        if start is None:
            raise ValueError(f"Guest label missing: {pc:08x}")
        end = next((i for i in range(start + 1, len(lines))
                    if LABEL.fullmatch(lines[i].strip())), len(lines))
        previous = old if apply else new + f" /* {MARKER} */"
        following = new + f" /* {MARKER} */" if apply else old
        hits = [i for i in range(start + 1, end)
                if lines[i].strip() == previous]
        if len(hits) != 1:
            raise ValueError(f"Expected one original statement {pc:08x}:{op_i}, got {len(hits)}")
        i = hits[0]
        end_chars = "\r\n" if lines[i].endswith("\r\n") else "\n"
        edited[i] = " " + following + end_chars
    output = "".join(edited).encode("utf8")
    if len(blob.splitlines()) != len(output.splitlines()):
        raise ValueError("Guest source line count changed")
    if output.count(MARKER.encode()) != (len(replacements) if apply else 0):
        raise ValueError("Unexpected marker count")
    return output


def stage_transform(srcs: dict[int, Path], pcode: Path, *, apply: bool):
    """Verify both source files before mutating either one."""
    originals = {p: src.read_bytes() for p, src in srcs.items()}
    patches = {}
    if apply:
        for part, blob in originals.items():
            if _sha(blob) != SOURCE_SHA256[part]:
                raise ValueError(f"Unknown original p{part} source or double apply")
        planned = plan(pcode)
        patches = {p: transform(originals[p], part=p, replacements=planned[p],
                                apply=True) for p in srcs}
    else:
        marked = [p for p, blob in originals.items() if MARKER.encode() in blob]
        if not marked:
            return originals, originals
        planned = plan(pcode)
        for part, blob in originals.items():
            markers = blob.count(MARKER.encode())
            if markers not in (0, len(planned[part])):
                raise ValueError(f"Partial p{part} patch")
            if markers:
                patches[part] = transform(blob, part=part,
                                          replacements=planned[part], apply=False)
                if _sha(patches[part]) != SOURCE_SHA256[part]:
                    raise ValueError(f"Cannot restore p{part} byte-for-byte")
            else:
                patches[part] = blob
    return originals, patches


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("p0", type=Path)
    ap.add_argument("p8", type=Path)
    ap.add_argument("pcode", type=Path)
    flags = ap.add_mutually_exclusive_group(required=True)
    flags.add_argument("--apply", action="store_true")
    flags.add_argument("--restore", action="store_true")
    args = ap.parse_args(argv)
    srcs = {0: args.p0, 8: args.p8}
    if (args.p0.name != "codsp_recomp_p0.c"
            or args.p8.name != "codsp_recomp_p8.c"):
        ap.error("This patch only targets original CoDSP p0 and p8")
    originals, output = stage_transform(srcs, args.pcode, apply=args.apply)
    stages = {}
    try:
        for part, data in output.items():
            if data == originals[part]:
                continue
            tmp = srcs[part].with_name(srcs[part].name + ".narrowleft.tmp")
            if tmp.exists():
                raise ValueError("Staging collision")
            tmp.write_bytes(data)
            if tmp.read_bytes() != data:
                raise IOError("Failed staged byte verification")
            stages[part] = tmp
        for part, tmp in stages.items():
            tmp.replace(srcs[part])
    except Exception:
        for part in stages:
            if srcs[part].exists() and srcs[part].read_bytes() != originals[part]:
                srcs[part].write_bytes(originals[part])
        raise
    finally:
        for tmp in stages.values():
            if tmp.exists():
                tmp.unlink()
    print("ARM64_NARROW_LEFT", "apply" if args.apply else "restore",
          "changed_parts", [p for p in srcs if output[p] != originals[p]],
          "sha", {str(p):_sha(srcs[p].read_bytes()) for p in srcs})


if __name__ == "__main__":
    main()
