#!/usr/bin/env python3
"""Idempotently add a **disabled-by-default** 32-byte copy fast path to
privately generated CoDSP.exe C.

No PE, PK3, raw p-code or generated C is committed. The injected code is
compiled ONLY with CODRECOMP_CODSP_COPY32_FASTPATH=ON; the default build
follows the exact original recompiled labels. Refuse unexpected layouts.
"""
from __future__ import annotations
import argparse
from pathlib import Path

HEADER = '// Generated by tools/recomp/pcode2c.py from CoDSP.exe. Do not commit.'
INCLUDE = '''#if defined(CODRECOMP_CODSP_COPY32_FASTPATH)
#include "codsp_copy32.h"
#endif
'''
ANCHOR = 'L_42b100:\n'
HOOK = '''#if defined(CODRECOMP_CODSP_COPY32_FASTPATH)
    if (codsp_copy32_step(R, MEM)) goto L_42b13e;
#endif
'''
# Verify 2003 original CoDSP copy-loop structure, not just an address match.
LABELS = [
    0x42b100, 0x42b103, 0x42b107, 0x42b10a,
    0x42b10e, 0x42b112, 0x42b116, 0x42b11a,
    0x42b11e, 0x42b122, 0x42b126, 0x42b12a,
    0x42b12e, 0x42b132, 0x42b136, 0x42b13a, 0x42b13e,
]
ENTRY = 0x42b100
EXIT = 0x42b13e


def patch_generated_source(contents: str) -> tuple[str, bool]:
    if not contents.startswith(HEADER) or '#include "recomp_rt.h"' not in contents[:350]:
        raise ValueError("Refusing non-CoDSP private generated C")
    if contents.count(ANCHOR) != 1:
        raise ValueError("Expected exactly one original 0x42b100 block")
    begin = contents.index(ANCHOR)
    end = contents.find("L_42b141:", begin)
    if end < 0 or end-begin > 12000:
        raise ValueError("Original 32-byte MOV loop boundaries not found")
    loop = contents[begin:end]
    if any(loop.count(f'L_{addr:x}:') != 1 for addr in LABELS):
        raise ValueError("Original 32-byte MOV loop labels changed")
    # The original code has eight dword loads/writes, alternating, with
    # EAX/ESI containing the final pair. A translator change fails closed.
    for fragment in (
        'wr(R+0x0,4,', 'wr(R+0x18,4,',
        'rd(R+0xc,4)', 'rd(R+0x8,4)', 'rd(R+0x1c,4)',
        'goto L_42b100',
    ):
        if fragment not in contents[begin:begin + 14000]:
            raise ValueError(f"Original copy loop invariant changed: {fragment}")
    present = HOOK in contents and INCLUDE in contents
    if present:
        if contents.count(HOOK) != 1 or contents.count(INCLUDE) != 1:
            raise ValueError("Partial or duplicate fast path")
        return contents, False
    if (HOOK in contents) != (INCLUDE in contents):
        raise ValueError("Incomplete previous patch")
    if 'CODRECOMP_CODSP_COPY32_FASTPATH' in contents:
        raise ValueError("Unexpected previous copy32 code")
    updated = contents.replace('#include "recomp_rt.h"\n',
                                '#include "recomp_rt.h"\n' + INCLUDE, 1)
    updated = updated.replace(ANCHOR, ANCHOR + HOOK, 1)
    return updated, True


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("file", type=Path)
    args = ap.parse_args()
    if not args.file.is_file():
        ap.error("Private generated CoDSP C is required; run the p-code generation first")
    # Never write the developer's source tree or arbitrary user file.
    if args.file.name != "codsp_recomp_p1.c" or args.file.parent.name != "recomp_out":
        ap.error("Only ignored recomp_out/codsp_recomp_p1.c is supported")
    raw = args.file.read_text(encoding="utf-8")
    result, changed = patch_generated_source(raw)
    if changed:
        args.file.write_text(result, encoding="utf-8", newline="\n")
    print("CoDSP 1.5 copy32 fastpath:", "added to private generated C" if changed else "already present",
          "(disabled unless CODRECOMP_CODSP_COPY32_FASTPATH=ON)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
