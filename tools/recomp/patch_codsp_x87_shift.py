#!/usr/bin/env python3
"""Reversible, byte-preserving x87 seven-COPY outlining of verified CoDSP C.

Use after private p-code generation and before compiling Android. No proprietary
sources/assets are embedded. Without --apply, --restore is idempotent.
"""
from __future__ import annotations
import argparse
import hashlib
from pathlib import Path

from x87_stack_fusion import PATTERNS

PCODE_SHA256="36f9093b386e03b4bcdc489cff2a708f7c0b8012e9a0fa78a7001bd3f125da1e"
HEADER="// Generated by tools/recomp/pcode2c.py from CoDSP.exe. Do not commit."
MARKER="/* CODSP_X87_SHIFT_OUTLINED */"

def _body_lines(pattern, base, prefix, newline):
    return [f"{prefix}wr({base}+0x{dest:x},10,rd({base}+0x{src:x},10));{newline}"
            for dest,src in pattern]

def _marker_lines(direction, base, prefix, newline):
    return [f"{prefix}codsp_x87_shift_{direction}({base}); {MARKER}{newline}"] + [
        f"{prefix};{newline}" for _ in range(6)
    ]

def transform(source: bytes, *, apply: bool):
    decoded=source.decode("utf-8")
    if not decoded.startswith(HEADER+"\n") and not decoded.startswith(HEADER+"\r\n"):
        raise ValueError("Not a verified pcode2c CoDSP source")
    if b"\r\n" in source and source.count(b"\r\n")!=source.count(b"\n"):
        raise ValueError("Mixed line endings")
    newline="\r\n" if b"\r\n" in source else "\n"
    lines=decoded.splitlines(keepends=True)
    if decoded and not decoded.endswith(("\n","\r")):
        raise ValueError("Expected complete generated C text lines")
    out=[]
    idx=0
    counts={"push":0,"pop":0}
    while idx<len(lines):
        cur=lines[idx]
        # Markers must be well formed even in --apply mode. Normal builder
        # always restores before applying a fresh experimental candidate.
        if MARKER in cur:
            if apply:raise ValueError("Already outlined; restore before applying")
            found=False
            for direction in PATTERNS:
                for base in ("guest_regs","R"):
                    prefix=cur[:len(cur)-len(cur.lstrip())]
                    replacement=_marker_lines(direction,base,prefix,newline)
                    if lines[idx:idx+7]==replacement:
                        out.extend(_body_lines(PATTERNS[direction],base,prefix,newline))
                        idx+=7
                        counts[direction]+=1
                        found=True
                        break
                if found:break
            if not found:raise ValueError("Malformed outlined x87 sequence")
            continue
        if apply:
            replaced=False
            for direction,pattern in PATTERNS.items():
                for base in ("guest_regs","R"):
                    prefix=cur[:len(cur)-len(cur.lstrip())]
                    body=_body_lines(pattern,base,prefix,newline)
                    if lines[idx:idx+7]==body:
                        out.extend(_marker_lines(direction,base,prefix,newline))
                        idx+=7
                        counts[direction]+=1
                        replaced=True
                        break
                if replaced:break
            if replaced:continue
        out.append(cur)
        idx+=1
    result="".join(out).encode("utf-8")
    if len(result.splitlines())!=len(lines):
        raise AssertionError("P-code C line numbering changed")
    return result,counts

def main():
    ap=argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("source",type=Path)
    ap.add_argument("pcode",type=Path)
    modes=ap.add_mutually_exclusive_group(required=True)
    modes.add_argument("--apply",action="store_true")
    modes.add_argument("--restore",action="store_true")
    args=ap.parse_args()
    if hashlib.sha256(args.pcode.read_bytes()).hexdigest()!=PCODE_SHA256:
        ap.error("Unknown CoDSP.exe 1.5 p-code; refusing code transformation")
    if args.source.name not in {f"codsp_recomp_p{i}.c" for i in range(12)}:
        ap.error("Can only transform the 12 generated CoDSP partition C files")
    original=args.source.read_bytes()
    rewritten,counts=transform(original,apply=args.apply)
    if rewritten!=original:
        staging=args.source.with_name(args.source.name+".shift.tmp")
        if staging.exists():raise RuntimeError("Refuse to overwrite staging output")
        try:
            staging.write_bytes(rewritten)
            if staging.read_bytes()!=rewritten:
                raise RuntimeError("Staging bytes verification failed")
            staging.replace(args.source)
        finally:
            if staging.exists():staging.unlink()
    print("X87_STACK_SHIFT",args.source.name,"apply" if args.apply else "restore",
          "patterns",counts,"modified",rewritten!=original,
          "sha256",hashlib.sha256(rewritten).hexdigest())
if __name__=="__main__": main()
